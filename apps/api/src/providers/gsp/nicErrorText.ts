/** Said when the portal refuses with a code this table does not know, and its own wording is missing too. */
export const unknownRefusalText = (code: string | null): string =>
  code
    ? `The GST portal refused the request (code ${code}). Check the details and try again.`
    : 'The GST portal refused the request. Check the details and try again.';

/**
 * Wording for a portal error: the portal's own when it sent some, else ours for its code. A message that is just the
 * code repeated (`"252"`) is no wording. Always something a person can read.
 */
export function nicErrorText(code: string | null, text: string | null | undefined): string {
  const given = (text ?? '').trim();
  if (given && given !== code) return given;
  return (code && NIC_ERROR_TEXT[code]) || unknownRefusalText(code);
}

/** Whether the table knows this code. */
export const knowsNicError = (code: string): boolean => code in NIC_ERROR_TEXT;
