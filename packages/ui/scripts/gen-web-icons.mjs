/** Reads an icon's node list, following the files Lucide keeps as aliases of another. */
function readNode(name, depth = 0) {
  let src;
  try {
    src = readFileSync(join(icons, `${name}.mjs`), 'utf8');
  } catch {
    return null;
  }
  const alias = src.match(/export \{ default \} from '\.\/(.+)\.mjs'/)?.[1];
  if (alias) return depth < 3 ? readNode(alias, depth + 1) : null;
  const body = src.match(/const __iconData = (\{[\s\S]*?\n\});/)?.[1];
  if (!body) return null;
  // The icon data is a JS literal of strings, arrays and plain objects; drop React keys.
  return Function(`return ${body}`)().node.map(([tag, { key: _key, ...attrs }]) => [tag, attrs]);
}

const data = {};
const missing = [];
for (const [mci, lucide] of Object.entries(MAP)) {
  const node = readNode(lucide);
  if (node) data[mci] = node;
  else missing.push(`${mci} -> ${lucide}`);
}

if (missing.length) {
  console.error(`No Lucide icon for:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const lines = Object.entries(data).map(([name, node]) => `  ${JSON.stringify(name)}: ${JSON.stringify(node)},`);
writeFileSync(
  out,
  `// Generated by packages/ui/scripts/gen-web-icons.mjs from lucide-react ${version} (ISC). Do not edit.
// Each entry is a Lucide drawing on a 24x24 grid, keyed by the MaterialCommunityIcons name it replaces.

export type IconNode = [tag: string, attrs: Record<string, string>][];

export const ICON_DATA: Record<string, IconNode> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${Object.keys(data).length} icons to ${out}`);
